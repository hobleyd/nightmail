#!/usr/bin/env python3
"""Generates lib/core/text/emoji_shortcodes.dart from iamcal's emoji-data,
the table Slack's own `:shortcode:` names come from.

    curl -sfL -o /tmp/emoji.json https://unpkg.com/emoji-datasource@15.1.2/emoji.json
    python3 tool/generate_emoji_shortcodes.py /tmp/emoji.json

Bump the emoji-datasource version to pick up new emoji; the output is
committed, so the app never fetches it.
"""
import json
import sys


def dart_escape(unified: str) -> str:
    return ''.join('\\u{%s}' % cp for cp in unified.split('-'))


def main(path: str) -> None:
    data = json.load(open(path, encoding='utf-8'))
    tones = {'1F3FB': 2, '1F3FC': 3, '1F3FD': 4, '1F3FE': 5, '1F3FF': 6}
    names = {}
    for e in sorted(data, key=lambda e: e['sort_order']):
        for name in e['short_names']:
            names.setdefault(name, e['unified'])
        # The exact toned sequence: in a joined emoji (a person raising a
        # hand) the tone sits after the person, not at the end.
        for key, variation in (e.get('skin_variations') or {}).items():
            if key in tones:
                for name in e['short_names']:
                    names.setdefault('%s::skin-tone-%d' % (name, tones[key]),
                                     variation['unified'])
    lines = [
        '// GENERATED by tool/generate_emoji_shortcodes.py from iamcal/emoji-data',
        '// (emoji-datasource on npm). Do not edit by hand.',
        '',
        '/// Every standard emoji by the `:shortcode:` names Slack uses, as the',
        '/// characters they stand for, and each skin-toned form as',
        '/// `name::skin-tone-N` (N 2-6). Workspace custom emoji are not here.',
        'const emojiShortcodes = <String, String>{',
    ]
    for name, unified in names.items():
        lines.append("  '%s': '%s'," % (name.replace("'", "\\'"), dart_escape(unified)))
    lines.append('};')
    out = 'lib/core/text/emoji_shortcodes.dart'
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('%d shortcodes -> %s' % (len(names), out))


if __name__ == '__main__':
    main(sys.argv[1])
